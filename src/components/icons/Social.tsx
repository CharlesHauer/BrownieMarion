export const socialMeta = {
  instagram: { Icon: InstagramIcon, label: "Instagram" },
  facebook: { Icon: FacebookIcon, label: "Facebook" },
  tiktok: { Icon: TiktokIcon, label: "TikTok" },
} as const;

export type SocialKey = keyof typeof socialMeta;
/** Donnée simple (sérialisable) : peut être passée à un composant client */
export type SocialLink = { key: SocialKey; href: string };

/** Réseaux renseignés (les adresses vides sont ignorées) */
export function getSocialLinks(
  reseaux: Partial<Record<SocialKey, string | undefined>>,
): SocialLink[] {
  return (Object.keys(socialMeta) as SocialKey[]).flatMap((key) => {
    const href = reseaux[key];
    return href ? [{ key, href }] : [];
  });
}

/** Icône + lien vers un réseau social */
export function SocialIconLink({
  link,
  className,
  iconClassName = "size-5",
}: {
  link: SocialLink;
  className?: string;
  iconClassName?: string;
}) {
  const { Icon, label } = socialMeta[link.key];
  return (
    <a
      href={link.href}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={label}
      className={className}
    >
      <Icon className={iconClassName} />
    </a>
  );
}
